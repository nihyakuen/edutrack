CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  role VARCHAR(20) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT chk_users_role CHECK (role IN ('ADMIN', 'TEACHER', 'STUDENT'))
);


CREATE TABLE study_groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(50) NOT NULL UNIQUE
);


CREATE TABLE students (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE,
  group_id BIGINT NOT NULL,
  CONSTRAINT fk_students_user FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT fk_students_group FOREIGN KEY (group_id) REFERENCES study_groups (id)
);


CREATE INDEX idx_students_group_id ON students (group_id);


CREATE TABLE subjects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(50) NOT NULL UNIQUE,
  name VARCHAR(255) NOT NULL
);


CREATE TABLE subject_assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id BIGINT NOT NULL,
  group_id BIGINT NOT NULL,
  teacher_id BIGINT NOT NULL,
  academic_year INTEGER NOT NULL,
  semester VARCHAR(20) NOT NULL,
  CONSTRAINT fk_subject_assignments_subject FOREIGN KEY (subject_id) REFERENCES subjects (id),
  CONSTRAINT fk_subject_assignments_group FOREIGN KEY (group_id) REFERENCES study_groups (id),
  CONSTRAINT fk_subject_assignments_teacher FOREIGN KEY (teacher_id) REFERENCES users (id),
  CONSTRAINT chk_subject_assignments_year CHECK (academic_year > 0),
  CONSTRAINT chk_subject_assignments_semester CHECK (semester IN ('SPRING', 'FALL')),
  CONSTRAINT uk_subject_assignments UNIQUE (subject_id, group_id, academic_year, semester)
);


CREATE INDEX idx_subject_assignments_teacher_id ON subject_assignments (teacher_id);


CREATE INDEX idx_subject_assignments_group_id ON subject_assignments (group_id);


CREATE TABLE lessons (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_assignment_id BIGINT NOT NULL,
  lesson_date DATE NOT NULL,
  topic VARCHAR(255) NOT NULL,
  CONSTRAINT fk_lessons_subject_assignment FOREIGN KEY (subject_assignment_id) REFERENCES subject_assignments (id)
);


CREATE INDEX idx_lessons_subject_assignment_id ON lessons (subject_assignment_id);


CREATE TABLE attendances (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lesson_id BIGINT NOT NULL,
  student_id BIGINT NOT NULL,
  status VARCHAR(20) NOT NULL,
  CONSTRAINT fk_attendances_lesson FOREIGN KEY (lesson_id) REFERENCES lessons (id),
  CONSTRAINT fk_attendances_student FOREIGN KEY (student_id) REFERENCES students (id),
  CONSTRAINT chk_attendances_status CHECK (status IN ('PRESENT', 'ABSENT', 'LATE', 'EXCUSED')),
  CONSTRAINT uk_attendances_student_lesson UNIQUE (student_id, lesson_id)
);


CREATE INDEX idx_attendances_lesson_id ON attendances (lesson_id);


CREATE TABLE assessments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_assignment_id BIGINT NOT NULL,
  title VARCHAR(255) NOT NULL,
  type VARCHAR(20) NOT NULL,
  assessment_date DATE NOT NULL,
  max_score INTEGER NOT NULL,
  CONSTRAINT fk_assessments_subject_assignment FOREIGN KEY (subject_assignment_id) REFERENCES subject_assignments (id),
  CONSTRAINT chk_assessments_type CHECK (type IN ('HOMEWORK', 'TEST', 'EXAM')),
  CONSTRAINT chk_assessments_max_score CHECK (max_score > 0)
);


CREATE INDEX idx_assessments_subject_assignment_id ON assessments (subject_assignment_id);


CREATE TABLE grades (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL,
  assessment_id BIGINT NOT NULL,
  score INTEGER NOT NULL,
  CONSTRAINT fk_grades_student FOREIGN KEY (student_id) REFERENCES students (id),
  CONSTRAINT fk_grades_assessment FOREIGN KEY (assessment_id) REFERENCES assessments (id),
  CONSTRAINT chk_grades_score CHECK (score >= 0),
  CONSTRAINT uk_grades_student_assessment UNIQUE (student_id, assessment_id)
);


CREATE INDEX idx_grades_assessment_id ON grades (assessment_id);